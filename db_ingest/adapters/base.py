"""Typed destination boundary; unavailable adapters fail before database activity."""
from typing import Any,Callable,Iterable,Protocol,runtime_checkable
from db_ingest.errors import IngestError
from db_ingest.models import SchemaPlan,RecordEnvelope,PublicationReceipt

@runtime_checkable
class DestinationAdapter(Protocol):
    name: str
    def quote_identifier(self,name:str)->str: ...
    def capabilities(self,config:dict,username=None,password=None)->dict: ...
    def connect(self,config:dict,username=None,password=None,database=None,autocommit=False)->Any: ...
    def inspect_schema(self,cursor:Any,plan:SchemaPlan)->dict: ...
    def map_type(self,type_name:str)->Any: ...
    def bootstrap(self,config:dict,database:str,username=None,password=None)->None: ...
    def stage_validate_publish(self,config:dict,plan:SchemaPlan,records:Callable[[],Iterable[RecordEnvelope]]|Iterable[RecordEnvelope],intent_id:str,run_id:str,username=None,password=None)->PublicationReceipt: ...
    def read_receipt(self,config:dict,plan:SchemaPlan,intent_id:str,username=None,password=None)->dict|None: ...
    def resolve_publication(self,config:dict,plan:SchemaPlan,intent_id:str,known_receipts=(),username=None,password=None,current_receipt=None)->dict: ...
    def reconcile(self,config:dict,plan:SchemaPlan,receipt:dict|PublicationReceipt,username=None,password=None)->dict: ...
    def categorize_error(self,error:Exception,operation:str,secrets=(),exit_code=4)->IngestError: ...


def require_mssql(config):
    kind=config.get('destination',{}).get('type','mssql')
    if kind!='mssql':raise IngestError('DESTINATION_UNSUPPORTED',f'{kind} is planned, not an implemented destination adapter')


def get_adapter(config)->DestinationAdapter:
    require_mssql(config)
    from .mssql.adapter import SqlServerAdapter
    return SqlServerAdapter()
